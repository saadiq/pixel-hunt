// Rasterises scenes/art/<id>.svg to src/scenes/<id>.ts. Usage: bun run build-scenes [id…]
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import type { Scene } from '../src/core/types';
import { parseMeta, rasterize } from './raster';

const ART = 'scenes/art';
const OUT = 'src/scenes';

const camel = (id: string) => id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

/** Renders a Scene as the TypeScript source of its generated data file. */
export function sceneSource(s: Scene): string {
  const q = (v: string) => JSON.stringify(v);
  const pal = Object.entries(s.pal).map(([ch, hex]) => `    ${ch}: '${hex}',`).join('\n');
  const rows = s.rows.map((r) => `    '${r}',`).join('\n');
  return `// Generated by build-scenes from scenes/art/${s.id}.svg. Do not edit: edit the SVG and run \`bun run build-scenes ${s.id}\`.
import type { Scene } from '../core/types';

export const ${camel(s.id)}: Scene = {
  id: ${q(s.id)},
  name: ${q(s.name)},
  blurb: ${q(s.blurb)},
  band: ${q(s.band)},
  slots: ${s.slots},
  lanes: ${s.lanes},
  chunk: [${s.chunk[0]}, ${s.chunk[1]}],
  wait: ${s.wait},
  pal: {
${pal}
  },
  rows: [
${rows}
  ],
};
`;
}

/** Builds one scene from its SVG. */
export function buildScene(svg: string): Scene {
  const m = parseMeta(svg);
  const vb = /viewBox="0 0 (\d+) (\d+)"/.exec(svg);
  if (!vb || +vb[1] !== m.W || +vb[2] !== m.H) throw new Error(`viewBox must be "0 0 ${m.W} ${m.H}"`);
  const art = rasterize(svg, m.W, m.H);
  return {
    id: m.id, name: m.name, blurb: m.blurb, band: m.band,
    slots: m.slots, lanes: m.lanes, chunk: m.chunk, wait: m.wait, ...art,
  };
}

if (import.meta.main) {
  const args = process.argv.slice(2).filter((a) => !a.startsWith('--'));
  const ids = args.length ? args : readdirSync(ART).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4));
  for (const id of ids) {
    try {
      const s = buildScene(readFileSync(`${ART}/${id}.svg`, 'utf8'));
      if (s.id !== id) throw new Error(`metadata id "${s.id}" does not match file name`);
      writeFileSync(`${OUT}/${id}.ts`, sceneSource(s));
      console.log(`wrote ${OUT}/${id}.ts  ${s.rows[0].length}x${s.rows.length}  ${Object.keys(s.pal).length} colours`);
    } catch (e) {
      console.error(`${id}: ${(e as Error).message}`);
      process.exitCode = 1;
    }
  }
}
